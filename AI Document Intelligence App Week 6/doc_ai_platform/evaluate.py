"""Measure how well the platform does on the labelled sample corpus.

Run:  python evaluate.py        (after  python make_samples.py)
Writes EVALUATION.md.

Important: the corpus is synthetic (generated by make_samples.py), so these numbers show
that the pipeline behaves as designed on known cases. They are NOT a claim about accuracy
on real-world documents, which would need a real labelled set.
"""
import json
import os
import statistics
import sys
import tempfile
import time
import warnings

warnings.filterwarnings("ignore")
HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)
sys.path.insert(0, HERE)

import config  # noqa: E402
import database as db  # noqa: E402
import rag  # noqa: E402
import service  # noqa: E402
import validator  # noqa: E402

tmp = tempfile.mkdtemp(prefix="docai_eval_")
config.DB_PATH = os.path.join(tmp, "documents.db")
config.STORAGE_ROOT = os.path.join(tmp, "storage")
db.init_db()

manifest = json.load(open("sample_docs/manifest.json"))
ids = {}
for e in manifest["documents"]:
    with open(os.path.join("sample_docs", e["file"]), "rb") as fh:
        ids[e["file"]] = service.upload_and_process(e["file"], fh.read())["upload"].doc_id
docs = {e["file"]: db.get_document(ids[e["file"]]) for e in manifest["documents"]}

# ---- classification
types = ["Invoice", "Resume", "Other"]
conf = {t: {p: 0 for p in types} for t in types}
for e in manifest["documents"]:
    conf[e["type"]][docs[e["file"]]["doc_type"]] += 1
correct = sum(conf[t][t] for t in types)
total = len(manifest["documents"])


def prf(label):
    tp = conf[label][label]
    fp = sum(conf[t][label] for t in types if t != label)
    fn = sum(conf[label][p] for p in types if p != label)
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    return p, r, (2 * p * r / (p + r) if p + r else 0.0)


# ---- field extraction (digital vs OCR)
def same(field, got, want):
    got, want = str(got).strip().lower(), str(want).strip().lower()
    if field == "skills":
        return set(got.replace(" ", "").split(",")) == set(want.replace(" ", "").split(","))
    return got == want


field_stats = {}
for e in manifest["documents"]:
    d = docs[e["file"]]
    for k, v in e["fields"].items():
        s = field_stats.setdefault((e["type"], k), {"ok": 0, "n": 0})
        s["n"] += 1
        s["ok"] += same(k, d["fields"].get(k, ""), v)
ocr_files = [e for e in manifest["documents"] if e["file"].startswith("scan_") and e["fields"]]
ocr_n = sum(len(e["fields"]) for e in ocr_files)
ocr_ok = sum(same(k, docs[e["file"]]["fields"].get(k, ""), v) for e in ocr_files for k, v in e["fields"].items())
all_n = sum(s["n"] for s in field_stats.values())
all_ok = sum(s["ok"] for s in field_stats.values())

# ---- workflow routing + reasons
route_ok = sum(docs[e["file"]]["status"] == e["status"] for e in manifest["documents"])
review_expected = [e for e in manifest["documents"] if e["status"] == "Needs Review"]


def reason_hit(e):
    d, why = docs[e["file"]], e.get("reason")
    if why in ("duplicate_identifier", "arithmetic_mismatch", "future_date", "unusual_amount"):
        return any(a["code"] == why for a in d["anomalies"])
    key = {"missing_fields": "Missing required", "invalid_fields": "Invalid field", "no_text": "No readable text",
           "unsupported_type": "no automated rules"}[why]
    return key in (d["review_reason"] or "")


reason_ok = sum(reason_hit(e) for e in review_expected)
clean = [e for e in manifest["documents"] if e["status"] == "Completed"]
false_alarms = sum(bool(docs[e["file"]]["anomalies"]) for e in clean)
anomaly_cases = [e for e in review_expected if e.get("reason") in
                 ("duplicate_identifier", "arithmetic_mismatch", "future_date", "unusual_amount")]
anomaly_hits = sum(reason_hit(e) for e in anomaly_cases)

# ---- upload protection
rej_ok = 0
for r in manifest["rejected_uploads"]:
    res = service.ingest(r["file"], open(os.path.join("sample_docs", r["file"]), "rb").read())
    rej_ok += (not res.ok) and res.code == r["expected_code"]

# ---- AI assistant
answerable = [
    ("What is the total amount on invoice HL-310?", "invoice_harbor.pdf", "$800.00"),
    ("What is the total amount on invoice NW-2043?", "invoice_northwind.pdf", "$2,530.00"),
    ("What is the total amount on invoice BB-77?", "invoice_bluebird.pdf", "$500.00"),
    ("What is the total on invoice LP-905?", "scan_invoice_lakeside.png", "$330.00"),
    ("What is the date of invoice PT-808?", "invoice_arithmetic_mismatch.pdf", "2025-04-02"),
    ("Who is the invoice from for number DW-55?", "invoice_missing_total.pdf", "DW-55"),
    ("What skills does Sara Khan have?", "resume_sara.pdf", "Machine Learning"),
    ("What is Ali Raza's email address?", "resume_ali.pdf", "ali.raza@mail.org"),
    ("What is the phone number of Hina Malik?", "scan_resume_hina.png", "+92 333 4445566"),
    ("What are Omar Farooq's skills?", "resume_missing_email.pdf", "Power BI"),
]
unanswerable = ["What is the warranty period for the product?", "Who is the president of France?",
                "What is the refund policy?", "How many employees does ACME have?",
                "What is the delivery address for the shipment?", "What is the weather in Karachi today?"]
src_ok = ans_ok = 0
misses = []
for q, fname, expect in answerable:
    res = rag.ask(q)
    s = bool(res["grounded"] and res["sources"] and res["sources"][0]["filename"] == fname)
    a = bool(res["grounded"] and expect.lower() in res["answer"].lower())
    src_ok += s
    ans_ok += a
    if not (s and a):
        misses.append((q, res["answer"][:90]))
refused = sum((not rag.ask(q)["grounded"]) for q in unanswerable)

# ---- timing
by_method = {"pdf-text": [], "ocr": []}
for d in docs.values():
    if d["timings"] and d["text_method"] in by_method:
        by_method[d["text_method"]].append(d["timings"])
stage_names = ["read_file", "text_extraction", "classification", "field_extraction", "validation",
               "anomaly_check", "ai_indexing", "total"]


def avg(rows, stage):
    return round(statistics.mean(r[stage] for r in rows), 1) if rows else 0.0


m = db.metrics()
lines = [
    "# Evaluation", "",
    f"Run on {time.strftime('%Y-%m-%d')} with `python evaluate.py` over the synthetic corpus in `sample_docs/` "
    f"({total} documents + {len(manifest['rejected_uploads'])} invalid files, all generated by `make_samples.py` "
    "with known ground truth).", "",
    "> **How to read these numbers:** the corpus is small, synthetic and written for this project. The results show that "
    "the pipeline does what it was designed to do on known cases. They do not predict accuracy on real invoices or "
    "CVs, which are messier. Replace `sample_docs/` with real labelled documents to measure that.", "",
    "## 1. Classification (keyword rules)", "",
    f"Accuracy: **{correct}/{total} = {correct / total:.0%}**", "",
    "| Class | Precision | Recall | F1 |", "|---|---|---|---|"]
for t in types:
    p, r, f = prf(t)
    lines.append(f"| {t} | {p:.2f} | {r:.2f} | {f:.2f} |")
lines += ["", "Confusion matrix (rows = true, columns = predicted):", "",
          "| true \\ predicted | Invoice | Resume | Other |", "|---|---|---|---|"]
for t in types:
    lines.append(f"| {t} | {conf[t]['Invoice']} | {conf[t]['Resume']} | {conf[t]['Other']} |")
lines += ["", "## 2. Field extraction", "",
          f"All fields: **{all_ok}/{all_n} = {all_ok / all_n:.0%}** correct "
          f"(scanned/OCR documents only: {ocr_ok}/{ocr_n} = {ocr_ok / ocr_n:.0%}).", "",
          "| Document type | Field | Correct | Total |", "|---|---|---|---|"]
for (t, k), s in sorted(field_stats.items()):
    lines.append(f"| {t} | {k} | {s['ok']} | {s['n']} |")
lines += ["", "## 3. Workflow decisions", "",
          f"- Correct final status (Completed / Needs Review): **{route_ok}/{total}**",
          f"- Needs-Review documents whose recorded reason matches the true cause: **{reason_ok}/{len(review_expected)}**",
          f"- Anomaly cases caught (duplicate number/email, arithmetic mismatch, future date, unusual amount): "
          f"**{anomaly_hits}/{len(anomaly_cases)}**",
          f"- False alarms: clean documents wrongly flagged with an anomaly: **{false_alarms}/{len(clean)}**",
          f"- Invalid uploads rejected with the right reason (wrong type, fake content, corrupt, empty): "
          f"**{rej_ok}/{len(manifest['rejected_uploads'])}**", "",
          "## 4. AI assistant (local TF-IDF retrieval, answers quoted from document text)", "",
          f"- Answerable questions: correct document ranked first **{src_ok}/{len(answerable)}**; "
          f"correct value in the answer **{ans_ok}/{len(answerable)}**",
          f"- Unanswerable questions correctly refused (\"not enough information\"): **{refused}/{len(unanswerable)}**",
          f"- Questions logged: {m['questions_asked']} (unanswered: {m['questions_unanswered']})"]
if misses:
    lines += ["", "Misses:"] + [f"  - {q} -> {a}" for q, a in misses]
lines += ["", "## 5. Processing time (milliseconds per document, averaged)", "",
          f"Digital PDFs: {len(by_method['pdf-text'])} documents · Scanned images (OCR): {len(by_method['ocr'])} documents", "",
          "| Stage | Digital PDF | Scanned (OCR) |", "|---|---|---|"]
for s in stage_names:
    lines.append(f"| {s.replace('_', ' ')} | {avg(by_method['pdf-text'], s)} | {avg(by_method['ocr'], s)} |")
slow_ocr = max((s for s in stage_names if s != "total"), key=lambda s: avg(by_method["ocr"], s))
slow_pdf = max((s for s in stage_names if s != "total"), key=lambda s: avg(by_method["pdf-text"], s))
lines += ["", f"**Bottleneck:** for scanned documents the slowest stage is *{slow_ocr.replace('_', ' ')}* "
              f"({avg(by_method['ocr'], slow_ocr)} ms); for digital PDFs it is *{slow_pdf.replace('_', ' ')}* "
              f"({avg(by_method['pdf-text'], slow_pdf)} ms). OCR results are cached by file hash and documents that were "
              "already processed are never reprocessed.", "",
          "## 6. Known limits", "",
          "- Classification uses keyword rules unless a trained model is placed at `MODEL_PATH`; rules give no confidence value.",
          "- Extraction is regex-based and tuned to labelled English invoices/resumes (\"Invoice No:\", \"Total Amount:\" ...).",
          "- The assistant is lexical (TF-IDF), so it matches words, not meaning: a question phrased with synonyms the "
          "documents never use may be refused.",
          "- A repeated invoice number is flagged on the *later* document; the earlier one is not changed.",
          "- OCR quality depends on the scan; blurry or low-resolution images may be sent to review as unreadable."]
open("EVALUATION.md", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("\n".join(lines))
